/** Рамка вокруг контура и сам контур в процентах от этой рамки — для clip-path. */
export function cutBox(pts: Pt[]) {
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1]);
  const r: Rect = { x: Math.min(...xs), y: Math.min(...ys), w: 0, h: 0 };
  r.w = Math.max(...xs) - r.x; r.h = Math.max(...ys) - r.y;
  return { r, clip: clipIn(r, pts) };
}
export const clipIn = (r: Rect, pts: Pt[]) =>
  `polygon(${pts.map(([x, y]) => `${(((x - r.x) / r.w) * 100).toFixed(1)}% ${(((y - r.y) / r.h) * 100).toFixed(1)}%`).join(',')})`;

export const rectStyle = (r: Rect) => `left:${r.x}%;top:${r.y}%;width:${r.w}%;height:${r.h}%`;

